#!/usr/bin/env node
/**
 * Rebuilds packages/engine/src/sbom/popular-packages.ts, the small list of very popular package names the
 * slopsquat check compares against. Run by hand (it reads the network); the check itself never does.
 *
 *   node scripts/refresh-popular-packages.mjs
 *
 * npm: wooorm/npm-high-impact (MIT), ordered by downloads.
 * PyPI: hugovk/top-pypi-packages (a list of package names from public PyPI download statistics).
 */
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const COUNT = 300;
const OUT = join(dirname(fileURLToPath(import.meta.url)), "..", "packages/engine/src/sbom/popular-packages.ts");

const npmSource = await (await fetch("https://raw.githubusercontent.com/wooorm/npm-high-impact/main/lib/top.js")).text();
const npm = [...npmSource.matchAll(/^\s+'([^']+)',?$/gm)].map(match => match[1]).filter(name => !name.startsWith("@")).slice(0, COUNT);
const pypiJson = await (await fetch("https://hugovk.github.io/top-pypi-packages/top-pypi-packages.min.json")).json();
const pypi = pypiJson.rows.map(row => String(row.project).toLowerCase().replace(/[-_.]+/g, "-")).slice(0, COUNT);
if (npm.length < COUNT || pypi.length < COUNT) throw new Error("A source list was shorter than expected.");

const body = `/**
 * Very popular package names, for the typosquat signal of \`0security sbom check --registry\`. Generated by
 * scripts/refresh-popular-packages.mjs; refresh it by running that script and committing the result.
 * npm (unscoped, top ${COUNT} by downloads): wooorm/npm-high-impact, MIT licence.
 * PyPI (top ${COUNT}, normalised): hugovk/top-pypi-packages, built from public PyPI download statistics. The file is names only.
 * Snapshot: ${new Date().toISOString().slice(0, 10)}.
 */
export const POPULAR_NPM: readonly string[] = ${JSON.stringify(npm)};
export const POPULAR_PYPI: readonly string[] = ${JSON.stringify(pypi)};
`;
writeFileSync(OUT, body);
console.log(`Wrote ${npm.length} npm and ${pypi.length} PyPI names to ${OUT}`);
