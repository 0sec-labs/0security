#!/usr/bin/env node
/**
 * Writes crates/foxguard/THIRD-PARTY-LICENSES.md: every Rust crate that ships inside the foxguard binary
 * (normal dependencies only, for every platform), with its version, license and source.
 *
 *   node scripts/generate-rust-notices.mjs          write the file
 *   node scripts/generate-rust-notices.mjs --check  fail when the file is out of date
 *
 * Needs cargo. It reads Cargo.lock (`--locked`), so it works offline once the crates are cached.
 */
import { execFileSync } from "node:child_process";
import { existsSync, lstatSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const output = join(root, "crates/foxguard/THIRD-PARTY-LICENSES.md");

const metadata = JSON.parse(execFileSync("cargo", ["metadata", "--format-version", "1", "--locked"], { cwd: root, encoding: "utf8", maxBuffer: 256 * 1024 * 1024 }));
const byId = new Map(metadata.packages.map((p) => [p.id, p]));
const nodes = new Map(metadata.resolve.nodes.map((n) => [n.id, n]));
const start = metadata.packages.find((p) => p.name === "foxguard" && !p.source);
if (!start) throw new Error("the foxguard package was not found in cargo metadata");

// Follow normal (not dev or build) dependencies from foxguard.
const seen = new Set();
const queue = [start.id];
while (queue.length) {
  const id = queue.pop();
  if (seen.has(id)) continue;
  seen.add(id);
  for (const dep of nodes.get(id)?.deps ?? []) {
    if (dep.dep_kinds.some((k) => k.kind === null)) queue.push(dep.pkg);
  }
}

const rows = [...seen].map((id) => byId.get(id)).filter((p) => p.name !== "foxguard").sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));
const cell = (text) => String(text ?? "").replace(/\|/g, "\\|").replace(/\s+/g, " ").trim();
const lines = [
  "# Third-party licenses for the foxguard binary",
  "",
  "Generated by `node scripts/generate-rust-notices.mjs` from `Cargo.lock`. Do not edit by hand.",
  "",
  "Foxguard itself is available under MIT OR Apache-2.0. The tree-sitter grammars in `vendor/` are MIT licensed and keep their own `LICENSE` files. Each crate below is built into the binary under the license shown; where a crate offers a choice (`OR`), either license applies. See the source link for the full text.",
  "",
  `${rows.length} crates.`,
  "",
  "| Crate | Version | License | Source |",
  "|---|---|---|---|",
  ...rows.map((p) => `| ${cell(p.name)} | ${cell(p.version)} | ${cell(p.license ?? (p.license_file ? `see ${p.license_file}` : "unknown"))} | ${cell(p.repository ?? `https://crates.io/crates/${p.name}`)} |`),
  "",
];
const text = lines.join("\n");

// The output path sits in a checkout that may come from an untrusted change: never write through a link.
const outputKind = (() => { try { return lstatSync(output); } catch { return undefined; } })();
if (outputKind && !outputKind.isFile()) {
  console.error(`${output} is not a regular file (a symbolic link or a folder); refusing to touch it.`);
  process.exit(1);
}

if (process.argv.includes("--check")) {
  if (!existsSync(output) || readFileSync(output, "utf8") !== text) {
    console.error("crates/foxguard/THIRD-PARTY-LICENSES.md is out of date. Run: node scripts/generate-rust-notices.mjs");
    process.exit(1);
  }
  console.log("rust notices up to date");
} else {
  writeFileSync(output, text);
  console.log(`wrote ${output} (${rows.length} crates)`);
}
